  let currentLanguage = localStorage.getItem('mog_language') || 'en';
  if (!TRANSLATIONS[currentLanguage]) currentLanguage = 'en';

  function t(key, params = {}) {
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    let text = dict[key] || TRANSLATIONS.en[key] || key;
    if (params && typeof params === 'object') {
      Object.keys(params).forEach(p => {
        text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
      });
    }
    return text;
  }

  function getLanguage() {
    return currentLanguage;
  }

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    currentLanguage = lang;
    localStorage.setItem('mog_language', lang);
    document.documentElement.lang = lang;

    // Apply translations across all DOM elements marked with data-i18n
    applyTranslations();

    // Trigger custom event for reactive components
    window.dispatchEvent(new CustomEvent('mog:languagechange', { detail: { lang } }));

    // Show smooth toast
    if (window.showToast) {
      const lObj = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];
      window.showToast(`${lObj.flag} ${lObj.name}`, 'info');
    }
  }

  function applyTranslations() {
    // 1. Elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (key) {
        const val = t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.hasAttribute('placeholder')) el.placeholder = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // 2. Elements with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.dataset.i18nTitle;
      if (key) el.title = t(key);
    });

    // 3. Elements with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      if (key) el.placeholder = t(key);
    });

    // 4. Update dynamic labels
    const langFlagEl = document.getElementById('active-lang-flag');
    const langNameEl = document.getElementById('active-lang-name');
    const lObj = LANGUAGES.find(l => l.code === currentLanguage) || LANGUAGES[0];
    if (langFlagEl) langFlagEl.textContent = lObj.flag;
    if (langNameEl) langNameEl.textContent = lObj.name;

    // 5. Update language checkmarks in popover / drawer
    document.querySelectorAll('.lang-option-btn').forEach(btn => {
      const isSelected = btn.dataset.lang === currentLanguage;
      btn.classList.toggle('selected', isSelected);
      const chk = btn.querySelector('.lang-check');
      if (chk) chk.textContent = isSelected ? '✓' : '';
    });

    // 6. Update consumer rule text dynamically based on active currency
    if (window.state && window.CURRENCY_REGISTRY) {
      const reg = window.CURRENCY_REGISTRY.find(c => c.code === window.state.activeCurrency) || window.CURRENCY_REGISTRY[0];
      const wfRule = document.getElementById('workflow-simple-rule');
      if (wfRule) {
        wfRule.textContent = t('consumerRuleText', { name: reg.name, authority: reg.authority });
      }
      const statusGuar = document.getElementById('workflow-status-guarantee');
      if (statusGuar) statusGuar.textContent = t('parValueProtected');
    }
  }

  // Export globally
  window.i18n = {
    LANGUAGES,
    TRANSLATIONS,
    t,
    getLanguage,
    setLanguage,
    applyTranslations
  };

